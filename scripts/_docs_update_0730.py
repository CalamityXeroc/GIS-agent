# -*- coding: utf-8 -*-
"""更新 docs/cartography.md：补比例尺宽度下限与空白判据（UTF-8 落盘脚本，避开控制台 GBK 影响）"""
from pathlib import Path

p = Path("docs/cartography.md")
s = p.read_text(encoding="utf-8")

old = "| 比例尺 | 按地图比例尺反算，取 m×10^k（m∈1,2,4,5）中最接近图框宽 20–28% 的值；刻度必须整数；单位自动（<10 km 用米、否则千米） | 参考图：0 / 1,000 / 2,000 / 4,000 米 |"
new = "| 比例尺 | 按地图比例尺反算，取 m×10^k（m∈1,2,4,5）中最接近图框宽 20–28% 的值；刻度必须整数；单位自动（<10 km 用米、否则千米）；**元素宽度不得窄于「标签放得下」的下限（≥ max(45mm, 10mm×刻度数)，上限 90mm）** | 参考图：0 / 1,000 / 2,000 / 4,000 米 |"
if s.count(old) == 1:
    s = s.replace(old, new, 1)
    print("比例尺行已更新")
else:
    print("比例尺行匹配数:", s.count(old))

old2 = "- 检查项：图名字号/是否居中/是否溢出、图例标签是否残留多位小数、图例是否压住数据、比例尺刻度是否整数、"
new2 = "- 检查项：图名字号/是否居中/是否溢出、图例标签是否残留多位小数、图例是否压住数据、比例尺刻度是否整数（并核对元素宽度是否够放标签）、"
if s.count(old2) == 1:
    s = s.replace(old2, new2, 1)
    print("检查项行已更新")

# 追加一条实测注意（空白判据）
anchor = "7. **样式名随安装语言变化**"
note = """8. **空白判据要看「占比 + 层次」**：`map_frame_blank` 曾用"非白像素占比 < 0.15"直接判空白，
   但淡色系（Purples 最浅一级 #F2F0F7）会把整幅有效图面判成空白（实测 14 届四 a 密度图 0.12）。
   现在改为"非白占比低 **且** 灰度标准差低"双条件。
9. **比例尺元素宽度有下限**：ArcGIS 按元素宽度自适应条长，宽度过窄时千米刻度数字会叠成一团
   （实测 16mm 宽 → "0/0.5/1/2/3/4" 重叠）。渲染前按刻度数抬下限，保证标签可读。

7. **样式名随安装语言变化**"""
if anchor in s and "空白判据要看" not in s:
    s = s.replace(anchor, note, 1)
    print("实测注意已追加")

p.write_text(s, encoding="utf-8")
print("完成，共", len(s), "字节")
