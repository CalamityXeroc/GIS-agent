# -*- coding: utf-8 -*-
"""生成 giscli 的三个 shell 入口：``giscli.cmd`` / ``giscli.ps1`` / ``giscli``。

**为什么三个都要有**：cmd 和 PowerShell 只认 PATHEXT（``.CMD`` / ``.PS1``），
而 **Git Bash 不认 PATHEXT**——它只会执行无扩展名的文件，所以 ``giscli`` 这个
名字本身必须落一个 sh 脚本，Git Bash 里才敲得出来（之前只有 ``.cmd``，Git Bash
里敲 ``giscli`` 就是 command not found）。

三份脚本都只做三件事：定位仓库 → 把仓库 ``src`` 前置进 ``PYTHONPATH`` → 把参数
交给 ``python -m gis_cli.boot``。**这里不许出现任何候选解释器路径**：发现逻辑只有
``arcpy_bridge.discover_arcgis_pro_python()`` 一份（历史包袱：cmd 里抄的那份候选表
在 Pro 3.6→3.7 升级后指错了路）。

``repo_root=None`` 渲染的是「从脚本自身位置推仓库根」的仓库内版本（``scripts/``
下那几份就是它，整个目录拷走也不会指错）；给了绝对路径就写死（安装到
``%LOCALAPPDATA%\\Programs\\giscli`` 的版本用这个——它不在仓库里）。
"""

from __future__ import annotations

import locale
import os
from pathlib import Path

CMD_NAME = "giscli.cmd"
PS1_NAME = "giscli.ps1"
BASH_NAME = "giscli"

#: 没指定时交给 PATH 上的 python（shim 里再按 GISCLI_PYTHON / ARCGIS_PRO_PYTHON 覆盖）。
DEFAULT_PYTHON = "python"

#: 模板里的占位符。用 replace 而不是 format：模板里 % 和 {} 都太多（cmd 的
#: ``%ERRORLEVEL%``、PS 的 ``$env:``、bash 的 ``${VAR:-x}``），format 会打架。
_REPO_SLOT = "@@REPO_ROOT@@"
_BOOT_SLOT = "@@BOOT_PY@@"

_CMD_TEMPLATE = r"""@echo off
REM ---------------------------------------------------------------------------
REM giscli -- run the GIS Agent CLI (entry: python -m gis_cli.boot).
REM
REM ASCII + CRLF on purpose: cmd.exe parses .bat in the ANSI codepage, so UTF-8
REM comments get chopped into fake commands (verified: long REM lines with
REM Chinese text produced "'------' is not recognized" all over the console).
REM
REM This file is a thin forwarder. Interpreter discovery lives in
REM gis_cli.arcpy_bridge -- do NOT add candidate paths here. The old cmd copy of
REM that candidate table drifted from the Python one on the Pro 3.6 -> 3.7
REM upgrade, and giscli then pointed at a directory that no longer existed.
REM
REM Generated by install.py -- re-run "python install.py" if the repo moves.
REM ---------------------------------------------------------------------------
setlocal
@@REPO_ROOT@@
if not exist "%REPO_ROOT%\src\gis_cli\boot.py" (
    echo [giscli] repo not found: %REPO_ROOT%
    echo [giscli] re-run: python "%REPO_ROOT%\install.py"
    exit /b 3
)
set "PYTHONPATH=%REPO_ROOT%\src"
set "BOOT_PY=@@BOOT_PY@@"
if exist "%GISCLI_PYTHON%" set "BOOT_PY=%GISCLI_PYTHON%"
if exist "%ARCGIS_PRO_PYTHON%" set "BOOT_PY=%ARCGIS_PRO_PYTHON%"
if not exist "%BOOT_PY%" set "BOOT_PY=python"
"%BOOT_PY%" -m gis_cli.boot %*
exit /b %ERRORLEVEL%
"""

_CMD_REPO_FROM_SCRIPT = "\n".join(
    [
        r'set "SCRIPT_DIR=%~dp0"',
        r'if "%SCRIPT_DIR:~-1%"=="\" set "SCRIPT_DIR=%SCRIPT_DIR:~0,-1%"',
        r'for %%I in ("%SCRIPT_DIR%\..") do set "REPO_ROOT=%%~fI"',
    ]
)

_PS1_TEMPLATE = r"""# giscli -- PowerShell shim. Thin forwarder to: python -m gis_cli.boot
#
# ASCII on purpose: Windows PowerShell 5.1 decodes BOM-less .ps1 as ANSI, so a
# UTF-8 comment here becomes mojibake (and a quote in it becomes a syntax error).
# Do NOT add interpreter candidate paths: discovery lives in gis_cli.arcpy_bridge.
#
# Generated by install.py -- re-run "python install.py" if the repo moves.

$ErrorActionPreference = 'Stop'
@@REPO_ROOT@@
if (-not (Test-Path (Join-Path $RepoRoot 'src/gis_cli/boot.py'))) {
    Write-Error "[giscli] repo not found: $RepoRoot -- re-run: python install.py"
    exit 3
}
if ($env:PYTHONPATH) {
    $env:PYTHONPATH = "$RepoRoot/src;$env:PYTHONPATH"
} else {
    $env:PYTHONPATH = "$RepoRoot/src"
}
$BootPy = '@@BOOT_PY@@'
if ($env:GISCLI_PYTHON) { $BootPy = $env:GISCLI_PYTHON }
if ($env:ARCGIS_PRO_PYTHON) { $BootPy = $env:ARCGIS_PRO_PYTHON }
if (-not (Test-Path $BootPy)) { $BootPy = 'python' }
& $BootPy -m gis_cli.boot @args
exit $LASTEXITCODE
"""

_PS1_REPO_FROM_SCRIPT = (
    "$RepoRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path"
)

_BASH_TEMPLATE = r"""#!/usr/bin/env bash
# giscli -- Git Bash / MSYS shim. Thin forwarder to: python -m gis_cli.boot
#
# Git Bash ignores PATHEXT, so only this *extensionless* file makes "giscli"
# resolve there; giscli.cmd works in cmd/PowerShell only.
# Do NOT add interpreter candidate paths: discovery lives in gis_cli.arcpy_bridge.
#
# Generated by install.py -- re-run "python install.py" if the repo moves.
set -u
@@REPO_ROOT@@
if [ ! -f "$REPO_ROOT/src/gis_cli/boot.py" ]; then
    echo "[giscli] repo not found: $REPO_ROOT -- re-run: python install.py" >&2
    exit 3
fi
# Windows 上的 python 只认 Windows 路径，Git Bash 的 /e/... 要先转过来；
# 用 -m（混合形式 E:/a/b）而不是 -w：正斜杠在 bash 和 Windows python 里都合法。
if command -v cygpath >/dev/null 2>&1; then
    REPO_ROOT="$(cygpath -m "$REPO_ROOT")"
fi
PYTHONPATH="$REPO_ROOT/src${PYTHONPATH:+;$PYTHONPATH}"
export PYTHONPATH
# 先挑一个能跑的解释器来启动 boot：安装时记下的那个 / 显式覆盖 / PATH 上的 python。
# 显式覆盖可能已经失效（Pro 升级后 ARCGIS_PRO_PYTHON 常指旧目录），
# 所以要看文件在不在；失效就交给 boot 自己重新发现（它与 arcpy_bridge 同源）。
BOOT_PY='@@BOOT_PY@@'
if [ -n "${GISCLI_PYTHON:-}" ] && [ -x "$GISCLI_PYTHON" ]; then
    BOOT_PY="$GISCLI_PYTHON"
fi
if [ -n "${ARCGIS_PRO_PYTHON:-}" ] && [ -x "$ARCGIS_PRO_PYTHON" ]; then
    BOOT_PY="$ARCGIS_PRO_PYTHON"
fi
if [ ! -x "$BOOT_PY" ]; then
    BOOT_PY=python
fi
exec "$BOOT_PY" -m gis_cli.boot "$@"
"""

_BASH_REPO_FROM_SCRIPT = 'REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"'


def render_cmd(repo_root: str | None = None, python: str | None = DEFAULT_PYTHON) -> str:
    """Windows cmd 入口。``repo_root=None`` 表示从脚本位置推仓库根。"""
    repo_block = (
        _CMD_REPO_FROM_SCRIPT if repo_root is None else f'set "REPO_ROOT={repo_root}"'
    )
    return (
        _CMD_TEMPLATE.replace(_REPO_SLOT, repo_block).replace(
            _BOOT_SLOT, python or DEFAULT_PYTHON
        )
    )


def render_ps1(repo_root: str | None = None, python: str | None = DEFAULT_PYTHON) -> str:
    """PowerShell 入口（PATHEXT 里 .CMD 排在 .PS1 前面，所以 cmd 里优先走 .cmd）。"""
    repo_block = (
        _PS1_REPO_FROM_SCRIPT if repo_root is None else f"$RepoRoot = '{_win_path(repo_root)}'"
    )
    return (
        _PS1_TEMPLATE.replace(_REPO_SLOT, repo_block).replace(
            _BOOT_SLOT, python or DEFAULT_PYTHON
        )
    )


def render_bash(repo_root: str | None = None, python: str | None = DEFAULT_PYTHON) -> str:
    """Git Bash / MSYS 入口（无扩展名，Git Bash 只认这个）。"""
    repo_block = (
        _BASH_REPO_FROM_SCRIPT
        if repo_root is None
        else f"REPO_ROOT='{_posix_path(repo_root)}'"
    )
    return (
        _BASH_TEMPLATE.replace(_REPO_SLOT, repo_block).replace(
            _BOOT_SLOT, python or DEFAULT_PYTHON
        )
    )


def _win_path(value: str) -> str:
    r"""正斜杠 → 反斜杠（cmd / PowerShell 里 ``E:/a/b`` 也能用，只是难看）。"""
    return str(value).replace("/", "\\")


def _posix_path(value: str) -> str:
    """反斜杠 → 正斜杠：bash 里 ``\\`` 是转义符，混合路径更省心。"""
    return str(value).replace("\\", "/")


def render_all(repo_root: str | None = None, python: str | None = DEFAULT_PYTHON) -> dict:
    """三份脚本的 ``{文件名: 内容}``（内容统一用 ``\\n`` 换行）。"""
    return {
        CMD_NAME: render_cmd(repo_root, python),
        PS1_NAME: render_ps1(repo_root, python),
        BASH_NAME: render_bash(repo_root, python),
    }


def _encode(name: str, text: str) -> bytes:
    r"""按目标文件的要求编码：``.cmd``/``.ps1`` 用 CRLF，bash 用 LF。

    ASCII 是常态（仓库放在中文目录时才有例外）：cmd.exe 按 **ANSI 代码页**解析
    批处理，所以路径含中文时只能按 ANSI 编码落盘——存成 UTF-8 会把那行拆成几条
    乱码命令（"非 ASCII 注释炸批处理"就是这么来的）。
    """
    newline = "\n" if name == BASH_NAME else "\r\n"
    payload = text.replace("\n", newline)
    if name == BASH_NAME:
        # bash 不管编码（注释里的中文它当字节），UTF-8 才是对的默认
        return payload.encode("utf-8")
    try:
        return payload.encode("ascii")
    except UnicodeEncodeError:
        # cmd.exe / PowerShell 5.1 按 ANSI 代码页读批处理，所以只能按 ANSI 落盘
        return payload.encode(locale.getpreferredencoding(False) or "utf-8", "replace")


def write_shims(
    target_dir: Path | str,
    *,
    repo_root: str | None = None,
    python: str | None = None,
) -> list:
    """把三份脚本写进 ``target_dir``；返回 ``[(路径, 是否改动)]``。

    幂等：内容一样就不落盘（重复安装不会无谓地动 mtime）。
    """
    directory = Path(target_dir)
    directory.mkdir(parents=True, exist_ok=True)
    written: list = []
    for name, text in render_all(repo_root, python).items():
        path = directory / name
        payload = _encode(name, text)
        changed = not path.is_file() or path.read_bytes() != payload
        if changed:
            path.write_bytes(payload)
        written.append((path, changed))
    # Git Bash 只认可执行位；Windows 上 chmod 无效但也无害
    try:
        os.chmod(directory / BASH_NAME, 0o755)
    except OSError:  # pragma: no cover - 权限受限的文件系统
        pass
    return written
